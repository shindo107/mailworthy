#!/usr/bin/env python3
"""Write Mailworthy/TierData.lua from tools/tiers/data.py. Run: python3 tools/tiers/build.py"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import data  # noqa: E402

NAMES = {129: "First Aid", 197: "Tailoring", 165: "Leatherworking", 164: "Blacksmithing",
         202: "Engineering", 333: "Enchanting", 171: "Alchemy", 185: "Cooking"}
MAIN = {129: data.FIRST_AID, 197: data.TAILORING, 165: data.LEATHERWORKING, 164: data.BLACKSMITHING,
        202: data.ENGINEERING, 333: data.ENCHANTING, 171: data.ALCHEMY, 185: data.COOKING}
CONVERT_NAMES = {2318: "Light Leather", 2319: "Medium Leather", 4234: "Heavy Leather", 4304: "Thick Leather",
                 8170: "Rugged Leather"}


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    out = ["-- GENERATED by tools/tiers/build.py from tools/tiers/data.py: edit those, then run",
           "-- python3 tools/tiers/build.py. Research and rules: Tiers.lua, docs/PLAN.md \"Material tiers\".",
           "local _, ns = ...", "local T = ns.Tiers", "",
           "-- skill line -> { { itemID, skill at which the profession is done with it, name }, ... } by skill.",
           "T.DONE = {"]
    keep = {}
    for prof in sorted(MAIN):
        rows = {}
        for item, skill, name, *why in MAIN[prof]:
            assert item not in rows, (prof, item)
            assert 0 < skill < 300, (prof, item, skill)
            rows[item] = (skill, name, why[0] if why else "")
        for item, skill, name in data.OUT.get(prof, []):
            assert item not in rows, ("duplicate", prof, item, name)
            assert 0 < skill < 300, (prof, item, skill)
            rows[item] = (skill, name, "outside its main materials")
            keep.setdefault(prof, set()).add(item)
        if prof in (129, 185):  # First Aid and Cooking keep their listed items whatever the item's class
            keep.setdefault(prof, set()).update(rows)
        keep.setdefault(prof, set()).update(data.KEEP_FOREVER.get(prof, []))
        out.append("    [%d] = { -- %s" % (prof, NAMES[prof]))
        for item, (skill, name, why) in sorted(rows.items(), key=lambda kv: (kv[1][0], kv[0])):
            line = "        { %d, %d, %s }," % (item, skill, lua_str(name))
            if why:
                line = line.ljust(52) + " -- " + why
            out.append(line[:138])
        out.append("    },")
    out += ["}", "",
            "-- Materials a profession keeps beyond its trade-goods subclasses (Valuation.PROFESSION_MATS):",
            "-- skill line -> { [itemID] = true }. Levelling ones only (operator, 2026-11-06), plus the few",
            "-- kept for good (First Aid's 300-skill reagents, Oily Blackmouth, cooking fish filed as food).",
            "T.KEEP = {"]
    for prof in sorted(keep):
        ids = sorted(keep[prof])
        out.append("    [%d] = { -- %s" % (prof, NAMES[prof]))
        line = "       "
        for i in ids:
            part = " [%d] = true," % i
            if len(line) + len(part) > 118:
                out.append(line)
                line = "       "
            line += part
        out.append(line)
        out.append("    },")
    out += ["}", "",
            "-- Leather up-conversions (Leatherworking): past its own recipes a leather is kept while",
            "-- converting it is worth more at the auction house than selling it (Tiers.WorthConverting).",
            "T.CONVERT = {", "    [165] = {"]
    for item, into, count in data.CONVERT_LW:
        out.append("        [%d] = { into = %d, count = %d, name = %s }," % (item, into, count,
                                                                            lua_str(CONVERT_NAMES[into])))
    out += ["    },", "}", ""]
    path = os.path.join(HERE, "..", "..", "Mailworthy", "TierData.lua")
    with open(path, "w") as f:
        f.write("\n".join(out))
    print("wrote", os.path.normpath(path), sum(len(v) for v in MAIN.values()), "main rows")


if __name__ == "__main__":
    main()
